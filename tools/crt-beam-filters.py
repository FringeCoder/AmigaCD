#!/usr/bin/env python3
"""Generate, or check, the scaler filters in filters/CRT_Beam/.

    tools/crt-beam-filters.py           rewrite the files
    tools/crt-beam-filters.py --check   fail if a file differs from what this
                                        script writes, or breaks a rule below

Why a generator: the Beam files are 64 rows of numbers each, computed from one
parameter. Edited by hand, a row that drifts off a sum of 128 brightens or
darkens every pixel at that phase, and that only shows on a screen.

Why --check also checks the parser's rules: read_video_filter() in video.cpp
does not reject a bad file. A row count that does not divide N_PHASES (256), or
a tap outside -128..128, makes it load a nearest-neighbour filter in its place
and say so only on the serial console -- the OSD still shows the file's name.
"""
import math
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "filters" / "CRT_Beam"
PHASES = 64          # divides video.cpp's N_PHASES (256)
N_PHASES = 256

HEADER = ["# range -128..128", "# sum of line must not exceed the range!", ""]


def beam(p, sigma):
    """Four taps at source pixels -1, 0, +1, +2 for an output point p (0..1)
    of the way from pixel 0 to pixel 1: a Gaussian spot, normalised to 128."""
    w = [math.exp(-((k - p) ** 2) / (2 * sigma * sigma)) for k in (-1, 0, 1, 2)]
    total = sum(w)
    v = [round(x * 128 / total) for x in w]
    v[max(range(4), key=lambda j: v[j])] += 128 - sum(v)  # rounding remainder
    return v


def beam_file(desc, sigma):
    lines = HEADER + [
        f"# {desc}: a Gaussian beam spot, sigma {sigma} source pixels, {PHASES} phases.",
        "# For the HORIZONTAL filter: softens pixel edges along a line the way a",
        "# CRT's beam spot does, which an aperture-grille tube (vertical stripes)",
        "# does not do by itself. Even at phase 0 it blends the neighbours, so it",
        "# is not for the vertical filter when scanlines are on -- pair it with",
        "# CRT_Beam/Vertical_Sharp.txt. Generated by tools/crt-beam-filters.py.",
        "",
    ]
    lines += ["%4d,%4d,%4d,%4d" % tuple(beam(i / PHASES, sigma)) for i in range(PHASES)]
    return "\n".join(lines) + "\n"


def nn_file():
    lines = HEADER + [
        "# Nearest neighbour, for the VERTICAL filter. At an exact integer vertical",
        "# scale every output line lands on phase 0 and takes one source line whole,",
        "# so scanlines (Scandoubler FX: CRT 25/50/75%) stay crisp.",
        "# Generated by tools/crt-beam-filters.py.",
        "",
    ]
    half = PHASES // 2
    lines += ["   0, 128,   0,   0"] * half + ["   0,   0, 128,   0"] * half
    return "\n".join(lines) + "\n"


FILES = {
    "Beam_Light.txt": beam_file("CRT beam, light", 0.35),
    "Beam_Medium.txt": beam_file("CRT beam, medium", 0.45),
    "Beam_Soft.txt": beam_file("CRT beam, soft", 0.55),
    "Vertical_Sharp.txt": nn_file(),
}


def rules(name, text):
    """The parser's rules (video.cpp read_video_filter / scale_phases), plus a
    row sum of exactly 128 so no phase changes brightness."""
    errs, rows = [], []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split(",")
        try:
            taps = [int(x) for x in parts]
        except ValueError:
            errs.append(f"{name}:{n}: not four integers: {line!r}")
            continue
        if len(taps) != 4:
            errs.append(f"{name}:{n}: {len(taps)} taps, want 4")
            continue
        if any(t < -128 or t > 128 for t in taps):
            errs.append(f"{name}:{n}: tap outside -128..128: {taps}")
        if sum(taps) != 128:
            errs.append(f"{name}:{n}: row sums to {sum(taps)}, want 128")
        rows.append(taps)
    if not rows or N_PHASES % len(rows):
        errs.append(f"{name}: {len(rows)} rows, which does not divide {N_PHASES}")
    return errs


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit(__doc__)
    errs = []
    for name, text in FILES.items():
        path = OUT / name
        if check:
            have = path.read_text() if path.exists() else None
            if have != text:
                errs.append(f"{path}: differs from the generator (edited by hand? "
                            "change the script and rerun it)")
            errs += rules(name, have or "")
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            errs += rules(name, text)
    extra = sorted(p.name for p in OUT.glob("*") if p.name not in FILES)
    if extra:
        errs.append(f"{OUT}: files the generator does not write: {extra}")
    for e in errs:
        print("FAIL", e)
    if errs:
        sys.exit(1)
    print(("checked " if check else "wrote ") + ", ".join(FILES))


if __name__ == "__main__":
    main()
